/** Competitions offered in the create-contest picker (testOnly hidden). */
export function selectableCompetitions(): CompetitionDef[] {
  return COMPETITIONS.filter((c) => !c.testOnly);
}

/** 'h2h' only for weekly-stats contests explicitly set to h2h; everything
 *  else (points-format weekly, and all event contests) is 'points' — a flat
 *  cumulative-points standings/leaderboard with no head-to-head matchups. */
export function contestFormat(settings: ContestSettings): 'h2h' | 'points' {
  return settings.mode === 'weekly-stats' && settings.format === 'h2h' ? 'h2h' : 'points';
}

/** Parse a contest's stored settings jsonb, falling back to the competition
 *  default when the snapshot is missing/malformed (fail-soft on reads; the DB
 *  trigger is the write-side enforcer). */
export function parseContestSettings(def: CompetitionDef, raw: unknown): ContestSettings {
  const obj = raw && typeof raw === 'object' ? (raw as Record<string, unknown>) : null;
  const draftType = obj?.draftType === 'snake' || obj?.draftType === 'auction' ? obj.draftType : undefined;
  if (obj?.mode === 'weekly-stats') {
    return {
      mode: 'weekly-stats',
      offenders: typeof obj.offenders === 'number' ? obj.offenders : WEEKLY_DEFAULT.offenders,
      defenders: typeof obj.defenders === 'number' ? obj.defenders : WEEKLY_DEFAULT.defenders,
      format: obj.format === 'h2h' ? 'h2h' : 'points',
      maxTeams: typeof obj.maxTeams === 'number' ? obj.maxTeams : undefined,
      unlimitedTeams: typeof obj.unlimitedTeams === 'boolean' ? obj.unlimitedTeams : undefined,
      schedule:
        obj.schedule && typeof obj.schedule === 'object'
          ? (obj.schedule as WeeklyStatsSettings['schedule'])
          : undefined,
      draft: obj.draft === true,
      draftType,
    };
  }
  if (obj?.mode === 'event') {
    return {
      mode: 'event',
      flex: typeof obj.flex === 'number' ? obj.flex : EVENT_DEFAULT.flex,
      eventId: typeof obj.eventId === 'string' ? obj.eventId : undefined,
      maxTeams: typeof obj.maxTeams === 'number' ? obj.maxTeams : undefined,
      unlimitedTeams: typeof obj.unlimitedTeams === 'boolean' ? obj.unlimitedTeams : undefined,
      draft: obj.draft === true,
      draftType,
      division: obj.division === 'men' || obj.division === 'women' || obj.division === 'mixed' ? obj.division : undefined,
    };
  }
  return def.defaultSettings;
}
