// Fantasy competition registry — the single place that defines which real
// competitions a contest can point at, and how each one plays.
//
// Two contest MODES:
//   • 'weekly-stats' — season leagues with per-game player statlines (UFA, PUL,
//     WUL). Weekly roster of role-assigned players (offenders/defenders),
//     scored by the SCORING matrix per locked week.
//   • 'event'        — single-tournament competitions where only event-total
//     stats exist (USAU Nationals, WFDF). One flex roster drafted from event
//     rosters, locked once at event start, scored once from event totals
//     (see event-adapter.ts).
//
// A contest row stores a snapshot of these settings in fantasy_contests.settings
// (jsonb) at creation time — the DB composition trigger reads that snapshot, so
// changing defaults here never mutates existing contests.

export type CompetitionId =
  | 'ufa'
  | 'pul'
  | 'wul'
  | 'usau-club-nationals'
  | 'usau-college-nationals'
  | 'wfdf-wucc'
  | 'eucs';

export type ContestMode = 'weekly-stats' | 'event';

/** Which player pool a contest drafts from = fantasy_roster_slots.player_league. */
export type FantasyPlayerLeague = 'ufa' | 'pul' | 'wul' | 'usau' | 'wfdf' | 'euf';

/** Which slice of a USAU Nationals pool a league drafts from: 'all' = every
 *  division at the event, otherwise only players on that division's teams. */
export type FantasyDivision = 'all' | 'men' | 'women' | 'mixed';

export interface WeeklyStatsSettings {
  mode: 'weekly-stats';
  offenders: number;
  defenders: number;
  /** 'h2h' = head-to-head weekly matchups + standings; absent/'points' =
   *  cumulative total points (the original behavior). */
  format?: 'h2h' | 'points';
  maxTeams?: number;
  unlimitedTeams?: boolean;
  /** Generated by fantasy_generate_schedule_internal once a h2h schedule
   *  exists; absent until then. */
  schedule?: { regular: string[]; semifinal: string; final: string };
  /** Set true by fantasy_schedule_draft/fantasy_schedule_auction_draft once a
   *  draft is scheduled for this contest — restricts lineups to rows in
   *  fantasy_team_players (own it or add/drop it) instead of the open player
   *  pool. Mirrors the DB's settings->>'draft' jsonb flag (see
   *  fantasy_add_drop, fantasy_save_contest_roster migrations). */
  draft?: boolean;
  /** The commissioner's create-time pick. It preselects the draft setup form;
   *  once a fantasy_drafts row exists, that row's draft_type is authoritative. */
  draftType?: 'snake' | 'auction';
}

export interface EventSettings {
  mode: 'event';
  flex: number;
  /** The real event this contest scores against (usau_events.id /
   *  wfdf_events.id / euf_events.id), frozen at contest creation. */
  eventId?: string;
  maxTeams?: number;
  unlimitedTeams?: boolean;
  /** See WeeklyStatsSettings.draft. */
  draft?: boolean;
  /** See WeeklyStatsSettings.draftType. */
  draftType?: 'snake' | 'auction';
  /** Division the league drafts from (competitions with supportedDivisions
   *  only). Absent = 'all' — read it through contestDivision. Set once at
   *  creation; there is no edit after that. */
  division?: FantasyDivision;
}

export type ContestSettings = WeeklyStatsSettings | EventSettings;

export interface CompetitionDef {
  id: CompetitionId;
  /** Full label for pickers/headers ("USAU Club Nationals"). */
  label: string;
  /** Compact label for chips/badges ("Club Nats"). */
  shortLabel: string;
  mode: ContestMode;
  playerLeague: FantasyPlayerLeague;
  defaultSettings: ContestSettings;
  /** weekly-stats only: league tracks yardage (UFA/WUL yes, PUL no → 0 pts). */
  hasYards: boolean;
  /** Hidden from the create-contest picker; usable only via direct code paths.
   *  WFDF/WUCC is our live test bed until Hunter opts it in. */
  testOnly: boolean;
}

const WEEKLY_DEFAULT: WeeklyStatsSettings = { mode: 'weekly-stats', offenders: 4, defenders: 3, format: 'h2h' };
const EVENT_DEFAULT: EventSettings = { mode: 'event', flex: 7 };

/** Weekly lineups start exactly 4 offense + 3 defense — fixed by the game, not
 *  a commissioner setting (Hunter, 2026-10-08; fantasy_update_contest_roster
 *  enforces it). */
export const WEEKLY_OFFENSE = 4;
export const WEEKLY_DEFENSE = 3;
export const WEEKLY_STARTERS = WEEKLY_OFFENSE + WEEKLY_DEFENSE;

/** Players per team = draft rounds, fixed by the game (Hunter, 2026-10-07):
 *  weekly 12 (7 starters + 5 bench), event 7 (no bench — drafted once, set
 *  for the whole event). fantasy_schedule_draft enforces the same numbers. */
export function teamSize(settings: ContestSettings): number {
  return settings.mode === 'event' ? 7 : 12;
}

/** Team-limit stepper bounds for Create a League and Settings → Teams. */
export const MIN_TEAMS = 4;
export const MAX_TEAMS = 16;
// Matches the DB trigger's coalesce(maxTeams, 12) and mobile.
export const DEFAULT_MAX_TEAMS = 12;

/** Team-cap stops for Create a League → Total teams and Settings → Teams. The
 *  last, ∞, is stored as unlimitedTeams with maxTeams DEFAULT_MAX_TEAMS
 *  (fantasy_set_contest_limits range-checks maxTeams even when unlimited). */
export const TEAM_LIMIT_STOPS = [4, 5, 6, 7, 8, 9, 10, 12, 16, Infinity];

/** Divisions a league can draft from, per competition. College Nationals has no
 *  Mixed. Competitions not listed have no division choice. */
const DIVISIONS_BY_COMPETITION: Partial<Record<CompetitionId, FantasyDivision[]>> = {
  'usau-club-nationals': ['all', 'men', 'women', 'mixed'],
  'usau-college-nationals': ['all', 'men', 'women'],
};

/** [] when the competition has no division choice. */
export function supportedDivisions(id: CompetitionId): FantasyDivision[] {
  return DIVISIONS_BY_COMPETITION[id] ?? [];
}

const DIVISION_LABELS: Record<FantasyDivision, string> = {
  all: 'All divisions',
  men: "Men's",
  women: "Women's",
  mixed: 'Mixed',
};

export function divisionLabel(division: FantasyDivision): string {
  return DIVISION_LABELS[division];
}

/** A contest's division; absent (and every weekly-stats contest) is 'all'. */
export function contestDivision(settings: ContestSettings): FantasyDivision {
  return settings.mode === 'event' ? (settings.division ?? 'all') : 'all';
}

/** " · Men's" to append after a game label; "" for All. */
export function divisionSuffix(settings: ContestSettings): string {
  const division = contestDivision(settings);
  return division === 'all' ? '' : ` · ${divisionLabel(division)}`;
}

